#!/usr/bin/env python3
"""diff-report.py dir report.md name...: compares <name>.swift.wav with <name>.fluid.wav (stdlib only)."""
import math, struct, sys, wave
d, report, names = sys.argv[1], sys.argv[2], sys.argv[3:]
def load(p):
    w = wave.open(p); n = w.getnframes(); ch = w.getnchannels()
    x = struct.unpack("<%dh" % (n * ch), w.readframes(n))
    return [(x[i * ch] + x[i * ch + ch - 1]) / 65536 for i in range(n)]
def db(v): return 20 * math.log10(max(v, 1e-9))
def env(x, w=441): return [db(math.sqrt(sum(s * s for s in x[i:i + w]) / w)) for i in range(0, len(x) - w, w)]
def f0(x, a, b):
    seg = x[a:b]; z = [i for i in range(1, len(seg)) if seg[i - 1] < 0 <= seg[i]]
    return 44100 * (len(z) - 1) / (z[-1] - z[0]) if len(z) > 2 else float("nan")
# Regression gate: max |deviation| per column, set just above the values measured on main
# (CI run 39903017964, 2026-10-22: RMS 18.73 dB, shape 7.93 dB, f0 127.5 cents, tail 0.65 s).
# Override with DIFF_MAX_RMS_DB / DIFF_MAX_SHAPE_DB / DIFF_MAX_F0_CENTS / DIFF_MAX_TAIL_S.
import os
LIMITS = {"rms": float(os.environ.get("DIFF_MAX_RMS_DB", 19.5)), "shape": float(os.environ.get("DIFF_MAX_SHAPE_DB", 8.5)),
          "cents": float(os.environ.get("DIFF_MAX_F0_CENTS", 135)), "tail": float(os.environ.get("DIFF_MAX_TAIL_S", 0.75))}
# Per-case baselines (measured on main, unchanged by the gbk sync of 2026-10-25; identical with FluidSynth 2.3 in CI
# and 2.4.4 locally). A case fails when it moves more than TOL from its own baseline, which is much tighter than the
# global limits above (renders are deterministic). Override the tolerances with DIFF_TOL_*; DIFF_NO_BASELINE=1 skips.
BASE = {  # name: (rms dB, shape dB, f0 cents, tail s)
    "piano-C4": (-18.09, 1.57, 0.0, -0.06), "piano-C2-ff": (-18.73, 1.56, -6.0, -0.06), "piano-C6-pp": (-8.15, 3.11, 0.1, -0.65),
    "nylon-guitar": (-15.01, 1.84, -10.9, 0.0), "violin": (-11.73, 2.40, -49.9, -0.01), "strings": (-17.84, 7.93, -127.5, -0.04),
    "trumpet": (-13.17, 2.46, -16.7, -0.01), "flute": (-9.69, 2.69, 0.0, 0.0), "organ": (-11.54, 1.93, 0.0, -0.03),
    "bass": (-14.95, 1.86, 0.0, -0.01), "kick": (-10.15, 0.26, float("nan"), 0.0), "snare": (-9.46, 0.32, -25.7, 0.0),
    "closed-hat": (-17.82, 0.49, float("nan"), -0.05)}
TOL = {"rms": float(os.environ.get("DIFF_TOL_RMS_DB", 0.5)), "shape": float(os.environ.get("DIFF_TOL_SHAPE_DB", 1.0)),
       "cents": float(os.environ.get("DIFF_TOL_F0_CENTS", 5)), "tail": float(os.environ.get("DIFF_TOL_TAIL_S", 0.1))}
USE_BASE = os.environ.get("DIFF_NO_BASELINE") != "1"
fails = []
rows = []
for n in names:
    try: s, f = load(f"{d}/{n}.swift.wav"), load(f"{d}/{n}.fluid.wav")
    except Exception as e: rows.append(f"| {n} | error: {e} | | | | |"); fails.append(f"{n}: error {e}"); continue
    m = min(len(s), len(f)); s, f = s[:m], f[:m]
    es, ef = env(s), env(f)
    pk = max(max(es), max(ef))
    rms = lambda x: db(math.sqrt(sum(v * v for v in x) / len(x)))
    shape = max((abs((a - max(es)) - (b - max(ef))) for a, b in zip(es, ef) if a > pk - 60 and b > pk - 60), default=float("nan"))
    a0, b0 = int(0.2 * 44100), int(0.6 * 44100)
    fs_, ff = f0(s, a0, b0), f0(f, a0, b0)
    cents = 1200 * math.log2(fs_ / ff) if fs_ > 0 and ff > 0 else float("nan")
    last = lambda e: next((i for i in range(len(e) - 1, -1, -1) if e[i] > max(e) - 60), 0) * 0.01
    vals = {"rms": rms(s) - rms(f), "shape": shape, "cents": cents, "tail": last(es) - last(ef)}
    for k, v in vals.items():
        if not math.isnan(v) and abs(v) > LIMITS[k]: fails.append(f"{n}: {k} {v:+.2f} exceeds +/-{LIMITS[k]}")
    if USE_BASE and n in BASE:
        for k, b in zip(("rms", "shape", "cents", "tail"), BASE[n]):
            v = vals[k]
            if math.isnan(b) != math.isnan(v) or (not math.isnan(v) and abs(v - b) > TOL[k]):
                fails.append(f"{n}: {k} {v:+.2f} moved from baseline {b:+.2f} (tolerance {TOL[k]})")
    rows.append(f"| {n} | {vals['rms']:+.2f} | {shape:.2f} | {cents:+.1f} | {vals['tail']:+.2f} |")
with open(report, "w") as o:
    o.write("# SF2Engine .spec vs FluidSynth\n\nGenerated by `scripts/diff-fluidsynth` (reverb/chorus off on both sides).\n"
            "Columns: overall RMS difference (dB, Swift - Fluid); max envelope-shape difference (dB, each normalised to its\n"
            "own peak, 10 ms windows above -60 dB); f0 difference 0.2-0.6 s (cents; nan for unpitched); end of audible tail\n"
            "difference (s). Expected deviations (spec followed, FluidSynth differs): linear pan law, 2.01 default\n"
            "modulators (no 2.04 velocity->filter), no-controller source = 1, filter Q DC rule.\n\n"
            "| case | RMS dB | shape dB | f0 cents | tail s |\n|---|---|---|---|---|\n")
    o.write("\n".join(rows) + "\n")
    o.write("\nLimits (|value|): RMS %.2f dB, shape %.2f dB, f0 %.1f cents, tail %.2f s.\n" % (LIMITS["rms"], LIMITS["shape"], LIMITS["cents"], LIMITS["tail"]))
    if USE_BASE: o.write("Per-case baseline tolerance: RMS %.2f dB, shape %.2f dB, f0 %.1f cents, tail %.2f s.\n" % (TOL["rms"], TOL["shape"], TOL["cents"], TOL["tail"]))
    o.write(("\n**FAIL**\n\n" + "\n".join("- " + x for x in fails) + "\n") if fails else "\n**PASS**: all cases within limits.\n")
if fails:
    print("diff-fluidsynth: deviation regression\n" + "\n".join(fails), file=sys.stderr); sys.exit(1)
